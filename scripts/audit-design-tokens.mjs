// 2. Disallowed Shape Tokens (Non-M3 Radius)
const FORBIDDEN_SHAPE_REGEX = /(border-radius:\s*(7px|10px|14px|15px|18px|20px|22px|24px|32px)|rounded-\[(7px|10px|14px|15px|18px|20px|22px|24px|32px)\]|--radius-lg:\s*24px|--radius-md:\s*14px)/gi;

// 3. Disallowed Heavy Elevation Shadows
const FORBIDDEN_SHADOW_REGEX = /(box-shadow:\s*0\s+20px\s+40px|box-shadow:\s*0\s+25px\s+50px|box-shadow:\s*0\s+10px\s+30px\s+rgba\(0,\s*0,\s*0,\s*0\.[789]\))/gi;

// 4. Undersized Touch Target (< 38px)
const UNDERSIZED_TARGET_REGEX = /(class="[^"]*\b(h-6|h-7|h-8|w-7|w-8)\b[^"]*"|height:\s*(24px|28px|30px|32px);)/gi;

// 5. Forbidden RGBA Patterns (Slate & ad-hoc RGB colors: 15, 23, 42 / 30, 41, 59 / 2, 132, 199 / 225, 29, 72)
const FORBIDDEN_RGBA_REGEX = /rgba\(\s*(15,\s*23,\s*42|30,\s*41,\s*59|2,\s*132,\s*199|225,\s*29,\s*72|56,\s*189,\s*248,\s*0\.[1-9]|251,\s*113,\s*133)\b[^)]*\)/gi;

// 6. Forbidden Card Linear Gradients on dark theme
const FORBIDDEN_CARD_GRADIENT_REGEX = /(\.result-card|\.card)\s*\{[^}]*background:\s*linear-gradient\([^)]*rgba\(\s*(15|30)/gi;

let totalViolations = 0;

function auditFile(filePath) {
  const content = fs.readFileSync(filePath, 'utf-8');
  const relativePath = path.relative(process.cwd(), filePath);
  const issues = [];

  // [Category 1: Navigation]
  if (filePath.endsWith('.html') && filePath.includes('public')) {
    if (!content.includes('href="/dashboard"') && !content.includes("href='/dashboard'") && !content.includes('href:"/dashboard"')) {
      issues.push('[M3 Navigation Whitelist] Missing mandatory back button linking to /dashboard');
    }
  }

  // [Category 2: Colors Whitelist]
  // In offline bundled single-file HTML, ignore compiled internal library engine bundles (pdf.js / react engine / fflate) and compiled Tailwind preflight CSS
  let codeToAudit = content;
  if (filePath.endsWith('.html')) {
    // Strip large compiled bundle script blocks (> 10000 chars) that contain engine binaries/internals
    codeToAudit = content.replace(/<script(?![^>]*type=["']text\/babel["'])[\s\S]*?<\/script>/gi, (m) => {
      return m.length > 10000 ? '' : m;
    });
    // Strip compiled Tailwind v3 CSS utility block (> 5000 chars) generated by build-tools
    codeToAudit = codeToAudit.replace(/<style(?![^>]*class=)[\s\S]*?<\/style>/gi, (m) => {
      return m.length > 5000 ? '' : m;
    });
  }

  const hexMatches = codeToAudit.match(/#[0-9a-fA-F]{3,8}\b/g) || [];
  const unapprovedHexes = new Set();
  for (const rawHex of hexMatches) {
    const hex = rawHex.toLowerCase();
    if (!APPROVED_HEX_WHITELIST.has(hex)) {
      unapprovedHexes.add(rawHex);
    }
  }
  if (unapprovedHexes.size > 0) {
    issues.push(`[M3 Color Whitelist] Disallowed hex color(s): ${[...unapprovedHexes].join(', ')}`);
  }

  // Raw Neon text misuse check
  const neonTextMatches = content.match(/color:\s*var\(--success\)\s*;/g);
  if (neonTextMatches) {
    issues.push('[M3 Vibrancy Whitelist] Disallowed raw neon text `color: var(--success);`. Use approved soft text (#34d399 / #6ee7b7)');
  }

  // Misusing .btn-success
  if (content.includes('class="btn btn-success"') || content.includes("class='btn btn-success'")) {
    issues.push('[M3 Button Role Whitelist] Misusing `.btn-success` for action buttons. Must use `.btn-primary`');
  }

  // [Category 3: Shape Scale Whitelist]
  const shapeMatches = content.match(FORBIDDEN_SHAPE_REGEX);
  if (shapeMatches) {
    issues.push(`[M3 Shape Whitelist] Non-M3 arbitrary radius detected: ${[...new Set(shapeMatches)].join(', ')}`);
  }

  // [Category 4: Elevation Whitelist]
  const shadowMatches = content.match(FORBIDDEN_SHADOW_REGEX);
  if (shadowMatches) {
    issues.push(`[M3 Elevation Whitelist] Disallowed heavy drop-shadow: ${[...new Set(shadowMatches)].join(', ')}`);
  }

  // [Category 4.1: RGBA & Gradient Whitelist]
  const rgbaMatches = content.match(FORBIDDEN_RGBA_REGEX);
  if (rgbaMatches) {
    issues.push(`[M3 Color Whitelist] Disallowed non-standard RGBA detected: ${[...new Set(rgbaMatches)].join(', ')}`);
  }
  const gradientMatches = content.match(FORBIDDEN_CARD_GRADIENT_REGEX);
  if (gradientMatches) {
    issues.push(`[M3 Surface Whitelist] Disallowed dark card gradient: ${[...new Set(gradientMatches)].join(', ')}`);
  }

  // [Category 5: Typography Whitelist]
  if (filePath.endsWith('.html')) {
    if (!content.includes('word-break: keep-all') && !content.includes('word-break:keep-all') && !content.includes('break-keep')) {
      issues.push('[M3 Typography Whitelist] Missing CJK word-break (word-break: keep-all / break-keep)');
    }
  }

  if (issues.length > 0) {
    totalViolations += issues.length;
    console.error(`\x1b[31m[FAIL]\x1b[0m ${relativePath}`);
    for (const issue of issues) {
      console.error(`  ↳ ${issue}`);
    }
  } else {
    console.log(`\x1b[32m[PASS]\x1b[0m ${relativePath}`);
  }
}

function walkDir(dir, filterExts) {
  if (!fs.existsSync(dir)) return;
  const files = fs.readdirSync(dir);
  for (const file of files) {
    const fullPath = path.join(dir, file);
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      if (file !== 'node_modules' && file !== '.next' && file !== '.git') {
        walkDir(fullPath, filterExts);
      }
    } else if (filterExts.some(ext => file.endsWith(ext))) {
      auditFile(fullPath);
    }
  }
}

console.log('========================================================================');
console.log('    WMS 2.0 Material Design 3 (M3) Multi-Object Strict Whitelist Audit  ');
console.log('========================================================================\n');

console.log('[Phase 1: Auditing Public Tools (public/tools/*.html)]');
walkDir(TOOLS_DIR, ['.html']);

console.log('\n[Phase 2: Auditing Application Routes & Components (src/**/*.tsx)]');
walkDir(SRC_DIR, ['.tsx']);

console.log('\n========================================================================');
if (totalViolations > 0) {
  console.error(`\x1b[31mAudit FAILED with ${totalViolations} Multi-Object Whitelist violation(s).\x1b[0m`);
  process.exit(1);
} else {
  console.log(`\x1b[32mAll files 100% strictly conform to M3 Multi-Object Whitelists! (0 violations)\x1b[0m`);
  process.exit(0);
}
